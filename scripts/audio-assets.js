// Static requires let Metro bundle only the compressed audition assets, never the WAVs or HTML.
const fs = require('node:fs');
const path = require('node:path');
const { cues, characters, emotions } = require('../design/audio/effects/catalog.cjs');
const manifest = require('../design/audio/effects/manifest.json');
const root = path.resolve(__dirname, '..');
const asset = (id) => {
  const entry = manifest.assets[id];
  if (!entry || !fs.existsSync(path.join(root, 'design/audio/effects', entry.mp3))) throw new Error(`Missing audio: ${id}`);
  return `{ id: '${id}', source: require('../../design/audio/effects/${entry.mp3}'), duration: ${entry.duration} }`;
};
const out = [
  '// Generated by node scripts/audio-assets.js. Sources stay in the audition collection.',
  "import type { SoundAsset } from './types';",
  'export const effects = {',
  ...cues.map(c => `  '${c.id}': [${Array.from({ length: c.variants }, (_, i) => asset(`${c.id}-${i + 1}`)).join(', ')}],`),
  '} satisfies Record<string, SoundAsset[]>;',
  'export type Cue = keyof typeof effects;',
  `export type Emotion = ${emotions.map(e => `'${e.id}'`).join(' | ')};`,
  'export const voices: Record<string, Record<Emotion, SoundAsset>> = {',
  ...characters.map(c => `  '${c.id}': {${emotions.map(e => `'${e.id}': ${asset(`voice-${c.id}-${e.id}`)}`).join(', ')}},`),
  '};',
  'export const music: SoundAsset[] = [',
  "  { id: 'detours', source: require('../../design/audio/first-listen/01-little-detours.mp3'), duration: 51.83 },",
  "  { id: 'window', source: require('../../design/audio/first-listen/02-sunday-window.mp3'), duration: 49.34 },",
  "  { id: 'updraft', source: require('../../design/audio/first-listen/03-updraft.mp3'), duration: 54.98 },",
  '];',
  '',
];
fs.mkdirSync(path.join(root, 'src/audio'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/audio/assets.ts'), out.join('\n'));
console.log(`Bundled inventory: ${cues.length} cues, ${characters.length * emotions.length} voices, 3 music tracks.`);
