// Static requires let Metro bundle only the compressed audition assets, never the WAVs or HTML.
const fs = require('node:fs');
const path = require('node:path');
const { cues, characters, emotions } = require('../design/audio/effects/catalog.cjs');
const manifest = require('../design/audio/effects/manifest.json');
const root = path.resolve(__dirname, '..');
const asset = (id) => {
  const entry = manifest.assets[id];
  if (!entry || !fs.existsSync(path.join(root, 'design/audio/effects', entry.mp3))) throw new Error(`Missing audio: ${id}`);
  return `{ id: '${id}', source: require('../../design/audio/effects/${entry.mp3}'), duration: ${entry.duration} }`;
};
// Playlist order. Durations come from each listening round's tracks.json.
const playlist = [
  ['detours', 'first-listen', '01-little-detours.mp3'],
  ['window', 'first-listen', '02-sunday-window.mp3'],
  ['updraft', 'first-listen', '03-updraft.mp3'],
  ['balloon', 'second-listen', '04-last-balloon.mp3'],
];
// Versus: each mode's match loop. Gapless AAC; duration is the exact loop length.
const loops = [
  ['rush', 'versus-listen', '05-photo-finish.m4a'],
  ['battle', 'versus-listen', '06-pop-rivals.m4a'],
  ['duel', 'versus-listen', '07-your-move.m4a'],
];
const track = ([id, round, file]) => {
  const entry = require(`../design/audio/${round}/tracks.json`).find(t => t.file === file);
  if (!entry || !fs.existsSync(path.join(root, 'design/audio', round, file))) throw new Error(`Missing music: ${file}`);
  const loop = entry.loop_seconds !== undefined;
  return `{ id: '${id}', source: require('../../design/audio/${round}/${file}'), duration: ${loop ? entry.loop_seconds : entry.seconds}${loop ? ', loop: true' : ''} }`;
};
const out = [
  '// Generated by node scripts/audio-assets.js. Sources stay in the audition collection.',
  "import type { SoundAsset } from './types';",
  'export const effects = {',
  ...cues.map(c => `  '${c.id}': [${Array.from({ length: c.variants }, (_, i) => asset(`${c.id}-${i + 1}`)).join(', ')}],`),
  '} satisfies Record<string, SoundAsset[]>;',
  'export type Cue = keyof typeof effects;',
  `export type Emotion = ${emotions.map(e => `'${e.id}'`).join(' | ')};`,
  'export const voices: Record<string, Record<Emotion, SoundAsset>> = {',
  ...characters.map(c => `  '${c.id}': {${emotions.map(e => `'${e.id}': ${asset(`voice-${c.id}-${e.id}`)}`).join(', ')}},`),
  '};',
  'export const music: SoundAsset[] = [',
  ...playlist.map(t => `  ${track(t)},`),
  '];',
  'export const loops = {',
  ...loops.map(t => `  ${t[0]}: ${track(t)},`),
  '} satisfies Record<string, SoundAsset>;',
  'export type MatchMusic = keyof typeof loops;',
  '',
];
fs.mkdirSync(path.join(root, 'src/audio'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/audio/assets.ts'), out.join('\n'));
console.log(`Bundled inventory: ${cues.length} cues, ${characters.length * emotions.length} voices, ${playlist.length} music tracks, ${loops.length} match loops.`);
